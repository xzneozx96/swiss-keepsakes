import { z } from 'zod'

// The codes the API sends: problem() in api/ takes no other, so a new code starts here. A client maps each one
// to translated copy (D11) and shows generic copy for any other code, so a page loaded before the API gained a
// code still reads the problem. `about:blank` means the HTTP status says everything there is to say.
export const problemTypes = [
  'about:blank',
  'not-found',
  'validation-failed',
  'internal-error',
  'unhealthy',
  'idempotency-key-required',
  'idempotency-key-reused',
  'idempotency-key-in-use',
  'body-too-large',
  'unauthenticated',
  'forbidden',
  'origin-refused',
  'store-slug-taken',
  'owner-is-super-admin',
  'invitation-not-found',
  'invitation-expired',
  'invitation-revoked',
  'invitation-super-admin',
  'invitation-already-accepted',
  'invitation-email-mismatch',
  'invitation-email-unverified',
  'already-a-member',
  'store-not-onboarding',
  'onboarding-incomplete',
  'manager-is-super-admin',
  'invitation-already-open',
  'cannot-remove-owner',
  'member-not-found',
  'precondition-failed',
  'precondition-required',
  'publish-incomplete',
  'media-retired',
  'media-invalid',
  'reference-invalid',
  'content-slug-taken',
  'slug-conflict',
  'published-cannot-be-deleted',
  'published-version-cannot-move',
  'version-exists',
  'not-published',
  'content-in-use',
  'media-type-not-allowed',
  'media-too-large',
  'media-empty',
  'upload-missing',
  'media-content-mismatch',
  'media-processing',
  'media-in-use',
  'media-already-retired',
  'media-not-ready',
  'media-kind-mismatch',
  'storage-unavailable',
  'category-has-children',
  'category-in-use',
  'category-too-deep',
  'category-parent-has-children',
  'sku-code-taken',
] as const

export type ProblemType = (typeof problemTypes)[number]

export const problemSchema = z.object({
  // A string on the wire, not an enum, for the reason above.
  type: z.string().meta({ description: `A stable code. Known codes: ${problemTypes.join(', ')}. Show generic copy for any other` }),
  status: z.int().min(400).max(599),
  title: z.string(),
  instance: z.string().meta({ description: 'The request path' }),
  requestId: z.string().meta({ description: 'The server\'s id for this request, also sent as X-Request-Id' }),
  errors: z.array(z.object({
    in: z.string(),
    path: z.string(),
    message: z.string(),
    code: z.string().optional().meta({ description: 'With a catalog refusal: a stable code the screen translates, such as value-in-use' }),
    params: z.record(z.string(), z.union([z.string(), z.number()])).optional().meta({ description: 'With a code: the numbers and names the message uses' }),
  })).optional(),
  pages: z.int().optional().meta({ description: 'With media-in-use: how many pages use the file' }),
  mediaIds: z.array(z.string()).optional().meta({ description: 'With media-processing: the ids of the files that are not ready yet' }),
  checks: z.record(z.string(), z.enum(['ok', 'failed'])).optional(),
}).meta({ id: 'Problem', description: 'RFC 9457 problem details, sent as application/problem+json' })

export type Problem = z.infer<typeof problemSchema>
