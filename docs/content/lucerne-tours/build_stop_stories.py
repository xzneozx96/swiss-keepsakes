#!/usr/bin/env python3
"""Turn the four research notes into front-end/src/features/tours/lucerne/stops.ts.

Stories, stop cards and notes are copied verbatim from the research files so the reviewed
text is what ships. Names and coordinates are set here because the notes give them in prose.
Re-run after editing a research file:  python3 -I docs/content/lucerne-tours/build_stop_stories.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
RESEARCH = ROOT / "docs/content/lucerne-tours/research"
OUT = ROOT / "front-end/src/features/tours/lucerne/stops.ts"
FILES = [
    "g1-city-core.md",
    "g2-musegg-churches-lion.md",
    "g3-palace-pharmacy-passes.md",
    "g4-gotthard-nufenen-rothorn-honey.md",
]

# slug -> (EN name, DE name, [lon, lat]) for the place the story is about.
PLACES = {
    "chapel-bridge": ("Chapel Bridge", "Kapellbrücke", [8.30724, 47.05134]),
    "kornmarkt": ("Kornmarkt and Town Hall", "Kornmarkt und Rathaus", [8.30609, 47.05196]),
    "weinmarkt": ("Weinmarkt", "Weinmarkt", [8.30482, 47.05201]),
    "hirschenplatz": ("Hirschenplatz", "Hirschenplatz", [8.30522, 47.05236]),
    "victorinox-store": ("Victorinox Store", "Victorinox Store", [8.30519, 47.05252]),
    "musegg-zyt": ("Musegg Wall and Zyt Tower", "Museggmauer und Zytturm", [8.30448, 47.05435]),
    "hofkirche": ("Hofkirche St. Leodegar", "Hofkirche St. Leodegar", [8.31406, 47.05567]),
    "lion-monument": ("Lion Monument", "Löwendenkmal", [8.31053, 47.05831]),
    "old-swiss-house": ("Old Swiss House", "Old Swiss House", [8.31126, 47.05728]),
    "jesuit-church": ("Jesuit Church", "Jesuitenkirche", [8.30515, 47.05044]),
    "ritter-palace": ("Ritter Palace", "Ritterscher Palast", [8.30424, 47.05040]),
    "suidter-pharmacy": ("Suidter pharmacy", "Suidter-Apotheke", [8.30287, 47.05021]),
    "furka": ("Hotel Belvédère and Rhône Glacier", "Hotel Belvédère und Rhonegletscher", [8.38839, 46.57665]),
    "grimsel": ("Grimsel Hospiz and Lake Grimsel", "Grimsel Hospiz und Grimselsee", [8.33233, 46.57154]),
    "susten": ("Susten Pass summit", "Sustenpass-Höhe", [8.44652, 46.72912]),
    "gotthard": ("Devil's Bridge, Schöllenen Gorge", "Teufelsbrücke, Schöllenenschlucht", [8.59029, 46.64736]),
    "nufenen": ("Nufenen Pass summit", "Nufenenpass-Höhe", [8.38783, 46.47712]),
    "brienzer-rothorn": ("Brienzer Rothorn summit", "Brienzer Rothorn Gipfel", [8.03940, 46.78746]),
    "finsterwald-honey": ("Finsterwald", "Finsterwald", [8.10274, 46.97322]),
}


def _line(block: str, label: str):
    m = re.search(rf"^{re.escape(label)}(?: \([^)]*\))?:[ \t]*(.*)$", block, re.M)
    return " ".join(m.group(1).split()) if m else None


def field(block: str, label: str) -> str:
    value = _line(block, label)
    if value is None:
        raise SystemExit(f"missing '{label}'")
    return value


def optional(block: str, label: str):
    return _line(block, label)


def sections(text: str):
    parts = re.split(r"^## ([a-z0-9-]+) — .*$", text, flags=re.M)
    for i in range(1, len(parts), 2):
        yield parts[i], parts[i + 1]


def sub(block: str, heading: str) -> str:
    m = re.search(rf"^### {re.escape(heading)}\s*$(.*?)(?=^### |\Z)", block, re.S | re.M)
    if not m:
        raise SystemExit(f"missing section '{heading}'")
    return m.group(1)


stories = {}
for name in FILES:
    for slug, block in sections((RESEARCH / name).read_text()):
        if slug not in PLACES:
            continue
        story, card = sub(block, "Story"), sub(block, "Stop card")
        stories[slug] = {
            "title": {"en": field(story, "EN title"), "de": field(story, "DE title")},
            "body": {"en": field(story, "EN body"), "de": field(story, "DE body")},
            "description": {"en": field(card, "EN description"), "de": field(card, "DE description")},
            "note": {k: v for k, v in (("en", optional(card, "EN note")), ("de", optional(card, "DE note"))) if v},
        }

missing = set(PLACES) - set(stories)
if missing:
    sys.exit(f"no story parsed for: {sorted(missing)}")
for slug, s in stories.items():
    for lang in ("en", "de"):
        words = len(s["body"][lang].split())
        if "ß" in s["body"][lang] + s["description"][lang]:
            sys.exit(f"{slug}: ß in {lang} text (Swiss spelling uses ss)")
        if not 70 <= words <= 130:
            print(f"warning: {slug} {lang} body is {words} words", file=sys.stderr)

lines = [
    "// Generated by docs/content/lucerne-tours/build_stop_stories.py from the research notes.",
    "// Edit the notes and re-run the script; do not hand-edit this file.",
    'import type { LocalizedText } from "@/features/catalog/types";',
    "",
    "export interface StopStory {",
    "  name: LocalizedText;",
    "  coordinates: [number, number];",
    "  title: LocalizedText;",
    "  body: LocalizedText;",
    "  description: LocalizedText;",
    "  note?: LocalizedText;",
    "}",
    "",
    "export const stopStories = {",
]
for slug, (en, de, coords) in PLACES.items():
    s = stories[slug]
    entry = {"name": {"en": en, "de": de}, "coordinates": coords, **s}
    if not entry["note"]:
        del entry["note"]
    lines.append(f"  {json.dumps(slug)}: {json.dumps(entry, ensure_ascii=False, indent=2)},")
lines += ["} satisfies Record<string, StopStory>;", "", "export type StopSlug = keyof typeof stopStories;", ""]

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines))
print(f"wrote {OUT.relative_to(ROOT)} with {len(stories)} stories")
