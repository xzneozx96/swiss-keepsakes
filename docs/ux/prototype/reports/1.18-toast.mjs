// 1.18 check of owner request 1.4b: fly-to-cart, badge bump, "Added to cart" toast with View cart. node toast.mjs en|de
import { writeFileSync } from "node:fs";
import { start, OUT } from "./1.18-lib.mjs";
const L = process.argv[2] || "en";
const S = await start();
const { page, T, check, text, shot, setLang, go } = S;
const sheet = () => page.getByRole("dialog").last();
await go(""); await page.evaluate(() => localStorage.clear()); await go(""); await setLang(L);
await go("#/gifts/chocolate-set", 1300);
await page.getByRole("button", { name: T("detail.bar.add"), exact: true }).last().click();
await sheet().waitFor(); await page.waitForTimeout(300);
await sheet().getByRole("gridcell").filter({ hasText: /^20$/ }).first().click();
await sheet().getByRole("radio", { name: /Altstadt/ }).check({ force: true });
await sheet().getByRole("button", { name: new RegExp("^" + T("detail.bar.add")) }).last().click();
await page.waitForTimeout(250);
const anims = await page.evaluate(() => document.getAnimations().length);
check("1.4b: fly-to-cart animation runs on add", anims > 0, anims);
await page.waitForTimeout(900);
const toast = page.locator(".toast").first();
const tt = S.norm(await toast.innerText());
check("1.4b: toast 'Added to cart' with item and View cart", tt.includes(T("cartToast.title")) && tt.includes(T("cartToast.viewCart")), tt);
check("1.4b: cart badge label counts 1 item", await page.getByRole("link", { name: T("nav.cartCount.one", { count: 1 }) }).count() > 0);
await shot("owner-1.4b-toast");
await toast.getByRole("button", { name: T("cartToast.viewCart") }).click();
await page.waitForTimeout(900);
check("1.4b: View cart opens #/cart", /#\/cart$/.test(page.url()), page.url());
check("no console or page errors", S.errors.length === 0, S.errors.join(" | "));
writeFileSync(`${OUT}/../../reports/1.18-results-toast-${L}.json`, JSON.stringify(S.results, null, 1));
console.log(`TOTAL ${S.results.filter((r) => r.pass).length} PASS, ${S.results.filter((r) => !r.pass).length} FAIL`);
await S.browser.close();
