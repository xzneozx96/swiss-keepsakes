import { chromium } from "playwright-core";
import { readdirSync } from "node:fs";
const home = `${process.env.HOME}/.cache/ms-playwright`;
const dir = readdirSync(home).filter((d) => d.startsWith("chromium_headless_shell")).sort().pop();
const browser = await chromium.launch({ executablePath: `${home}/${dir}/chrome-headless-shell-linux64/chrome-headless-shell` });
const B = "http://localhost:5243/";
let pass=0, fail=0; const check=(n,ok,d="")=>{ok?pass++:fail++;console.log(`${ok?"PASS":"FAIL"} ${n}${d?" | "+JSON.stringify(d):""}`)};
for (const [w,label] of [[1280,"desktop"],[375,"phone"]]) {
  const page = await browser.newPage({ viewport: { width: w, height: 900 } });
  const errs=[]; page.on("pageerror",e=>errs.push(String(e))); page.on("console",m=>m.type()==="error"&&errs.push(m.text()));
  await page.goto(B); await page.evaluate(()=>{localStorage.clear();localStorage.setItem("sk.language",'"en"')}); await page.reload(); await page.waitForTimeout(800);
  await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem("sk.demo")); s.role="owner"; localStorage.setItem("sk.demo",JSON.stringify(s));});
  await page.goto(B+"#/store/products"); await page.reload(); await page.waitForTimeout(1500);
  const menuBtn = page.getByRole("button",{name:"Actions for Lucerne postcard set"}).filter({visible:true});
  await menuBtn.click(); await page.waitForTimeout(300);
  check(`[${label}] menu shows Edit and Archive`, (await page.getByRole("menuitem").allInnerTexts()).join("|").replace(/\s/g,"")==="Edit|Archive".replace(/\s/g,""), await page.getByRole("menuitem").allInnerTexts());
  await page.getByRole("menuitem",{name:"Archive"}).click(); await page.waitForTimeout(400);
  check(`[${label}] still on M11 after choosing Archive`, page.url().endsWith("#/store/products"), page.url());
  const dlg=page.getByRole("alertdialog"); check(`[${label}] confirmation opens`, await dlg.isVisible());
  await dlg.getByRole("button",{name:"Archive"}).click(); await page.waitForTimeout(600);
  const p = await page.evaluate(()=>JSON.parse(localStorage.getItem("sk.demo")).data.products.find(p=>p.id==="p-postcards"));
  check(`[${label}] archived in data`, !!p.archivedAt && p.published===false, p.archivedAt);
  check(`[${label}] gone from Active`, !(await page.getByRole("button",{name:"Actions for Lucerne postcard set"}).filter({visible:true}).count()));
  await page.getByRole("row",{name:/Archived/}).first().click().catch(async()=>{await page.getByText(/^Archived/).first().click()}); await page.waitForTimeout(400);
  check(`[${label}] listed under Archived with the chip`, (await page.getByRole("button",{name:"Actions for Lucerne postcard set"}).filter({visible:true}).count())===1);
  await page.screenshot({path:`../run418/archive-${label}.png`});
  await page.goto(B+"#/gifts"); await page.reload(); await page.waitForTimeout(1200);
  const role=await page.evaluate(()=>JSON.parse(localStorage.getItem("sk.demo")).role);
  check(`[${label}] C02 hides the archived gift`, !(await page.locator("body").innerText()).includes("Lucerne postcard set"), role);
  await page.goto(B+"#/store/products"); await page.reload(); await page.waitForTimeout(1500);
  await page.getByText(/^Archived/).first().click(); await page.waitForTimeout(400);
  await page.getByRole("button",{name:"Actions for Lucerne postcard set"}).filter({visible:true}).click(); await page.waitForTimeout(300);
  await page.getByRole("menuitem",{name:"Restore as draft"}).click(); await page.waitForTimeout(500);
  const q = await page.evaluate(()=>JSON.parse(localStorage.getItem("sk.demo")).data.products.find(p=>p.id==="p-postcards"));
  check(`[${label}] restore makes it a draft`, !q.archivedAt && q.published===false);
  await page.getByText(/^Active/).first().click(); await page.waitForTimeout(400);
  await page.getByRole("button",{name:"Actions for Lucerne postcard set"}).filter({visible:true}).click(); await page.waitForTimeout(300);
  await page.getByRole("menuitem",{name:"Edit"}).click(); await page.waitForTimeout(800);
  check(`[${label}] Edit opens M12`, page.url().endsWith("#/store/products/gifts/p-postcards"), page.url());
  check(`[${label}] no console errors`, errs.length===0, errs.slice(0,2));
  await page.close();
}
await browser.close(); console.log(`RESULT ${pass} passed, ${fail} failed`);
