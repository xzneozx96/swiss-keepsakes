// 1.18: C04 remove still asks first in the shared ConfirmDialog after the 1.5c–1.5f cart rework. node remove.mjs en|de
import { writeFileSync } from "node:fs";
import { start, OUT } from "./1.18-lib.mjs";
const L = process.argv[2] || "en";
const S = await start(); const { page, go, setLang, T, check, shot, demo } = S;
const sheet = () => page.getByRole("dialog").last();
await go(""); await page.evaluate(() => localStorage.clear()); await go(""); await setLang(L);
await go("#/gifts/chocolate-set", 1200);
await page.getByRole("button", { name: T("detail.bar.add"), exact: true }).last().click(); await sheet().waitFor();
await sheet().getByRole("gridcell").filter({ hasText: /^20$/ }).first().click();
await sheet().getByRole("radio", { name: /Altstadt/ }).check({ force: true });
await sheet().getByRole("button", { name: new RegExp("^" + T("detail.bar.add")) }).last().click(); await page.waitForTimeout(500);
await go("#/cart", 1400);
for (const b of await page.locator(".toast__close-button").all()) await b.click({ force: true }).catch(() => {});
await page.getByRole("button", { name: new RegExp(T("cart.line.removeAria", { name: "" }).trim()) }).first().click();
await page.waitForTimeout(500);
const dlg = page.getByRole("alertdialog");
check("C04 remove opens the shared confirm dialog", await dlg.count() === 1);
check("C04 remove dialog: focus starts on Cancel", ((await page.evaluate(() => document.activeElement?.textContent)) || "").includes(T("confirm.cancel")));
await shot("c04-remove-confirm");
await page.keyboard.press("Escape"); await page.waitForTimeout(400);
check("C04 remove: Escape keeps the line", (await demo()).data.cart.length === 1);
await page.getByRole("button", { name: new RegExp(T("cart.line.removeAria", { name: "" }).trim()) }).first().click(); await page.waitForTimeout(500);
await page.getByRole("alertdialog").getByRole("button", { name: T("cart.remove.confirm") }).click(); await page.waitForTimeout(700);
check("C04 remove: confirming empties the cart and shows the empty state", (await demo()).data.cart.length === 0 && (await S.mainText()).includes(T("cart.empty.message")));
check("no console or page errors", S.errors.length === 0, S.errors.join(" | "));
writeFileSync(`${OUT}/../../reports/1.18-results-remove-${L}.json`, JSON.stringify(S.results, null, 1));
console.log(`TOTAL ${S.results.filter((r) => r.pass).length} PASS, ${S.results.filter((r) => !r.pass).length} FAIL`);
await S.browser.close();
