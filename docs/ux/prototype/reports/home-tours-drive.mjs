import { chromium } from "playwright-core";
const exe = process.env.HOME + "/.cache/ms-playwright/chromium_headless_shell-1243/chrome-headless-shell-linux64/chrome-headless-shell";
const OUT = process.argv[2], B = "http://localhost:5240/";
let pass = 0, fail = 0; const check = (n, ok, x = "") => { ok ? pass++ : fail++; console.log(ok ? "PASS" : "FAIL", n, x); };
const br = await chromium.launch({ executablePath: exe });
const page = await (await br.newContext({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 2 })).newPage();
const errs = []; page.on("pageerror", (e) => errs.push(e.message)); page.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await page.goto(B); await page.evaluate(() => localStorage.clear()); await page.goto(B + "#/"); await page.waitForTimeout(1500);
const sec = page.locator("section", { has: page.getByRole("heading", { name: /Staying a few days\?|Ein paar Tage hier\?/ }) }).last();
await sec.scrollIntoViewIfNeeded(); await page.waitForTimeout(500);
const txt = await sec.innerText();
console.log("TOURS:", txt.replace(/\n+/g, " | "));
check("no Coming soon on tours", !/Coming soon/i.test(txt));
check("real tour shown", /Lucerne old-town walk/.test(txt));
check("shared card: heart on each tour", (await sec.getByRole("button", { name: /Save|Saved|Remove/i }).count()) >= 3, String(await sec.getByRole("button", { name: /Save|Saved|Remove/i }).count()));
check("shared card: price pill", /from[\s\S]{0,3}CHF.89\.00/.test(txt), JSON.stringify(txt.match(/.{0,8}CHF.89\.00/)));
check("placeholder tours gone", !/Hidden Lucerne|Alpine Journey|Local Encounters/.test(txt));
await page.screenshot({ path: OUT + "/home-tours-en.png" });
await page.getByRole("group", { name: "Language" }).getByRole("button", { name: "DE" }).first().click(); await page.waitForTimeout(500);
await sec.scrollIntoViewIfNeeded(); const de = await sec.innerText(); console.log("DE:", de.replace(/\n+/g, " | "));
check("DE no Bald/Coming soon", !/Demnächst|Bald verfügbar|Coming soon/i.test(de));
await page.screenshot({ path: OUT + "/home-tours-de.png" });
await page.getByRole("group", { name: "Language" }).getByRole("button", { name: "EN" }).first().click(); await page.waitForTimeout(400);
await sec.getByRole("link", { name: /Lucerne old-town walk/ }).click(); await page.waitForTimeout(1200);
check("card opens tour detail", /#\/tours\/lucerne-old-town-walk$/.test(page.url()), page.url());
await page.goto(B + "#/search?q=walk"); await page.waitForTimeout(1200);
const s = await page.locator("main, body").first().innerText();
check("search finds real tour", /Lucerne old-town walk/.test(s) && !/Coming soon/.test(s.split("Stories")[0]), s.replace(/\n+/g, " | ").slice(0, 300));
await page.screenshot({ path: OUT + "/search-walk-en.png" });
const link = page.getByRole("link", { name: /Lucerne old-town walk/ }).first(); await link.click(); await page.waitForTimeout(1000);
check("search result opens tour detail", /#\/tours\/lucerne-old-town-walk$/.test(page.url()), page.url());
check("no overflow", await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
check("no console errors", errs.length === 0, errs.join(" ; ").slice(0, 300));
await br.close(); console.log(`${pass} passed, ${fail} failed`);
