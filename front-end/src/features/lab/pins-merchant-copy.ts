export type CopyKey = keyof typeof copy

const PLACEHOLDER = /\{(\w+)\}/g

/** `c('key', { name })` in the dashboard's language. */
export function useCopy() {
  const { language, intlLocale } = useLocale()

  const c = (key: CopyKey, vars?: Record<string, string | number>) => {
    const [en, de] = copy[key]

    return (language === 'de' ? de : en).replace(PLACEHOLDER, (_, name: string) =>
      String(vars?.[name] ?? `{${name}}`))
  }

  return { c, language, intlLocale }
}
